-- 6. PIQ SUBMISSIONS
CREATE TABLE piq_submissions (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    personal_details JSONB,
    education_details JSONB,
    hobbies_sports JSONB,
    ssb_history JSONB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Secure the table so users can only access their own data
ALTER TABLE piq_submissions ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can insert their own piq" ON piq_submissions FOR INSERT WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Users can select their own piq" ON piq_submissions FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Users can update their own piq" ON piq_submissions FOR UPDATE USING (auth.uid() = user_id);

-- Optional: Create index for faster querying by user_id
CREATE INDEX idx_piq_user_id ON piq_submissions(user_id);
