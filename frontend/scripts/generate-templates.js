const { createClient } = require('@supabase/supabase-js');
require('dotenv').config({ path: '.env.local' });
const fs = require('fs');
const path = require('path');

const supabase = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY);

const AUTOGEN_DIR = path.join(__dirname, '../src/lib/study-content/autogen');

async function run() {
  console.log('Fetching data from Supabase...');
  
  const { data: chaptersData, error: chaptersError } = await supabase
    .from('study_chapters')
    .select('id, name, study_subjects(exam_id)');
    
  if (chaptersError) throw chaptersError;

  const { data: topicsData, error: topicsError } = await supabase
    .from('study_topics')
    .select('id, title, chapter_id, read_time')
    .order('order_index');
    
  if (topicsError) throw topicsError;

  console.log(`Found ${chaptersData.length} chapters and ${topicsData.length} topics.`);

  // Group topics by chapter
  const topicsByChapter = {};
  for (const topic of topicsData) {
    if (!topicsByChapter[topic.chapter_id]) {
      topicsByChapter[topic.chapter_id] = [];
    }
    topicsByChapter[topic.chapter_id].push(topic);
  }

  // Create autogen directory
  if (!fs.existsSync(AUTOGEN_DIR)) {
    fs.mkdirSync(AUTOGEN_DIR, { recursive: true });
  }

  const exportStatements = [];
  const registryEntries = [];

  // Generate a file for each chapter
  for (const chapter of chaptersData) {
    const examId = chapter.study_subjects?.exam_id || 'unknown';
    const chapterTopics = topicsByChapter[chapter.id] || [];
    
    // We only need to write files for chapters that have topics
    if (chapterTopics.length === 0) continue;

    // Make sure exam directory exists
    const examDir = path.join(AUTOGEN_DIR, examId);
    if (!fs.existsSync(examDir)) {
      fs.mkdirSync(examDir, { recursive: true });
    }

    const fileName = `${chapter.id}.ts`;
    const filePath = path.join(examDir, fileName);
    
    // Convert chapter ID to a safe variable name
    const varName = `${chapter.id.replace(/-/g, '_').toUpperCase()}_AUTOGEN`;

    let fileContent = `import { TopicContent } from '../../types'\n\n`;
    fileContent += `export const ${varName}: TopicContent[] = [\n`;
    
    for (const topic of chapterTopics) {
      // Escape single quotes in title
      const safeTitle = topic.title.replace(/'/g, "\\'");
      const readTime = parseInt(topic.read_time) || 5;

      fileContent += `  {
    id: '${topic.id}',
    title: '${safeTitle}',
    readTimeMinutes: ${readTime},
    content: [
      { type: 'heading', data: '${safeTitle} Overview' },
      { type: 'text', data: 'This is the autogenerated study material for ${safeTitle}. The core concepts and detailed explanations for this topic will be available soon.' },
      { type: 'callout', data: '🚧 Content Under Development. Keep revising the key points!' },
      { type: 'list', data: [
        'Understand the basic principles of ${safeTitle}',
        'Review standard formulas and applications',
        'Practice related previous year questions'
      ]},
    ],
    keyPoints: [
      'Basic definition and scope of ${safeTitle}',
      'Important formulas and shortcuts',
      'Common question patterns in the exam'
    ],
    inlineQuiz: [
      { 
        question: 'What is the primary objective of studying ${safeTitle}?', 
        options: ['To memorize facts', 'To apply concepts to solve problems', 'To skip it in the exam', 'None of the above'], 
        correct: 1, 
        explanation: 'Applying concepts accurately is key to scoring well.' 
      }
    ]
  },\n`;
    }
    
    fileContent += `]\n`;
    fs.writeFileSync(filePath, fileContent);
    
    // Keep track for index.ts
    const importPath = `./${examId}/${chapter.id}`;
    exportStatements.push(`import { ${varName} } from '${importPath}'`);
    registryEntries.push(`  '${chapter.id}': ${varName},`);
  }

  // Generate index.ts
  const indexContent = `import { TopicContent } from '../types'\n\n`
    + exportStatements.join('\n') + `\n\n`
    + `export const AUTOGEN_REGISTRY: Record<string, TopicContent[]> = {\n`
    + registryEntries.join('\n') + `\n}\n`;

  fs.writeFileSync(path.join(AUTOGEN_DIR, 'index.ts'), indexContent);
  console.log('Successfully generated all templates and autogen registry!');
}

run().catch(console.error);
